#!/usr/bin/env python3
"""Uploads AFTERTIDE's generated assets to Roblox with the Open Cloud Assets API and writes
the resulting IDs into the game config.

  python3 tools/upload_assets.py --user-id 123456789            # everything
  python3 tools/upload_assets.py --user-id 123 --only models    # just the 3D packs
  python3 tools/upload_assets.py --group-id 456 --only audio    # upload as a group

The API key is read from the ROBLOX_API_KEY environment variable. In a Claude Code cloud
session the key is injected by the network proxy instead (it never appears here).
Writes: src/shared/Config/AssetIds.luau (packs) and src/shared/Config/Sounds.luau (audio),
then rebuilds build/Aftertide.rbxlx.
"""
import argparse
import json
import mimetypes
import os
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
API = "https://apis.roblox.com/assets/v1"
KEY = os.environ.get("ROBLOX_API_KEY", "injected-by-proxy")
PACKS = ["Crew", "Factions", "Hushed", "Weapons", "Nature", "Props"]
CONTENT_TYPES = {".glb": "model/gltf-binary", ".fbx": "model/fbx", ".ogg": "audio/ogg", ".mp3": "audio/mpeg"}


def _multipart(fields, file_field, filename, data, content_type):
    boundary = uuid.uuid4().hex
    out = bytearray()
    for name, value in fields.items():
        out += f"--{boundary}\r\nContent-Disposition: form-data; name=\"{name}\"\r\n\r\n{value}\r\n".encode()
    out += f"--{boundary}\r\nContent-Disposition: form-data; name=\"{file_field}\"; filename=\"{filename}\"\r\nContent-Type: {content_type}\r\n\r\n".encode()
    out += data + f"\r\n--{boundary}--\r\n".encode()
    return bytes(out), f"multipart/form-data; boundary={boundary}"


def _call(method, url, body=None, content_type=None):
    req = urllib.request.Request(url, data=body, method=method)
    req.add_header("x-api-key", KEY)
    if content_type:
        req.add_header("Content-Type", content_type)
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{e.code} {e.reason}: {e.read().decode(errors='replace')[:400]}")


def upload(path, asset_type, name, creator):
    ext = os.path.splitext(path)[1].lower()
    ctype = CONTENT_TYPES.get(ext) or mimetypes.guess_type(path)[0] or "application/octet-stream"
    request = {
        "assetType": asset_type,
        "displayName": name[:50],
        "description": "AFTERTIDE original asset (generated by tools)",
        "creationContext": {"creator": creator},
    }
    body, mp = _multipart({"request": json.dumps(request)}, "fileContent", os.path.basename(path), open(path, "rb").read(), ctype)
    op = _call("POST", f"{API}/assets", body, mp)
    op_id = op.get("operationId") or op.get("path", "").split("/")[-1]
    for _ in range(90):
        if op.get("done"):
            break
        time.sleep(2)
        op = _call("GET", f"{API}/operations/{op_id}")
    if not op.get("done"):
        raise RuntimeError("timed out waiting for Roblox to process " + name)
    resp = op.get("response") or {}
    asset_id = resp.get("assetId")
    if not asset_id:
        raise RuntimeError(f"no asset id for {name}: {json.dumps(op)[:400]}")
    return int(asset_id)


def set_pack_ids(ids):
    path = os.path.join(ROOT, "src", "shared", "Config", "AssetIds.luau")
    src = open(path).read()
    for pack, asset_id in ids.items():
        src = re.sub(r"(\n\t\t%s = )\d+" % pack, r"\g<1>%d" % asset_id, src)
    open(path, "w").write(src)


def set_sound_ids(ids):
    path = os.path.join(ROOT, "src", "shared", "Config", "Sounds.luau")
    src = open(path).read()
    for key, asset_id in ids.items():
        src = re.sub(r'(\n\t%s = )"[^"]*"' % re.escape(key), r'\g<1>"rbxassetid://%d"' % asset_id, src)
    open(path, "w").write(src)


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--user-id")
    g.add_argument("--group-id")
    ap.add_argument("--only", choices=["models", "audio"])
    ap.add_argument("--packs", nargs="*", default=PACKS)
    args = ap.parse_args()
    creator = {"userId": str(args.user_id)} if args.user_id else {"groupId": str(args.group_id)}

    if args.only in (None, "models"):
        ids = {}
        for pack in args.packs:
            path = os.path.join(ROOT, "assets", pack + ".glb")
            print(f"uploading {pack}.glb ...", flush=True)
            ids[pack] = upload(path, "Model", "AFTERTIDE " + pack, creator)
            print(f"  {pack} -> {ids[pack]}")
            set_pack_ids(ids)
    if args.only in (None, "audio"):
        ids = {}
        audio_dir = os.path.join(ROOT, "audio")
        for fname in sorted(os.listdir(audio_dir)):
            if not fname.endswith(".ogg"):
                continue
            key = fname[:-4]
            try:
                ids[key] = upload(os.path.join(audio_dir, fname), "Audio", "AFTERTIDE " + key, creator)
                print(f"  {key} -> {ids[key]}")
                set_sound_ids(ids)
            except RuntimeError as e:
                print(f"  {key} FAILED: {e}", file=sys.stderr)
    subprocess.run([sys.executable, os.path.join(HERE, "build_place.py")], check=True)
    print("Done. Open build/Aftertide.rbxlx (or re-publish) to use the uploaded assets.")


if __name__ == "__main__":
    main()
